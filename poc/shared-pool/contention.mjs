#!/usr/bin/env node
// Two fresh identities: complete funded rehearsal, then measured exit race.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {spawn,spawnSync} from 'node:child_process';
import {here,binary,sdkPath,fundingDir,read,save,number,fileHash,syncDirectory,transaction,rust,connect,utxos,startWallet,startWalletSidecar} from './runtime.mjs';
import {sleep,outpoint,outputUtxo,exactUtxo,confirm,acceptedSnapshot,canonicalRpcTx,successor} from './chain.mjs';

function sourceHashes(){
  const names=['Cargo.toml','Cargo.lock',...fs.readdirSync(path.join(here,'src')).filter(n=>n.endsWith('.rs')).map(n=>'src/'+n),...fs.readdirSync(here).filter(n=>n.endsWith('.mjs'))];
  return Object.fromEntries(names.sort().map(n=>[n,fileHash(path.join(here,n))]));
}
function assertRehearsal(base,sources){
  const passed=fs.readdirSync(base).map(n=>path.join(base,n)).filter(p=>fs.existsSync(path.join(p,'result.json'))).some(p=>{
    const r=read(path.join(p,'result.json')),prepared=read(path.join(p,'prepared.json'));
    return prepared.purpose==='rehearsal'&&r.success&&prepared.binarySha256===fileHash(binary)&&JSON.stringify(prepared.sources)===JSON.stringify(sources);
  });
  assert.ok(passed,'same implementation needs a completed funded rehearsal first');
}
async function prepare(params,base,purpose){
  assert.ok(['rehearsal','trial'].includes(purpose));fs.mkdirSync(base,{recursive:true,mode:0o700});
  const sources=sourceHashes();if(purpose==='trial')assertRehearsal(base,sources);
  const root=path.join(base,new Date().toISOString().replaceAll(':','-')+'-'+purpose+'-'+crypto.randomUUID());
  const init=spawnSync(binary,['init',params,root,'2'],{encoding:'utf8'});assert.equal(init.status,0,init.stderr);
  const logs=path.join(root,'logs'),publicDir=path.join(root,'public');fs.mkdirSync(logs,{mode:0o700});
  console.log(JSON.stringify({stage:'identity-created',root,purpose}));
  const {rpc,info}=await connect();
  try{
    const f=read(path.join(fundingDir,'funding.json'));assert.equal(f.network,'testnet-10');
    const inputs=(await utxos(rpc,f.address)).filter(u=>!u.is_coinbase&&BigInt(u.amount)>2_500_000_000n).sort((a,b)=>BigInt(a.amount)>BigInt(b.amount)?-1:1);
    assert.ok(inputs.length,'insufficient ordinary test funding');save(path.join(root,'funding-input.json'),inputs[0]);
    save(path.join(root,'node-before.json'),{info,feeEstimate:await rpc.getFeeEstimate()});
    rust(logs,'fund',['fund',root,path.join(root,'funding-input.json'),path.join(fundingDir,'funding.key')]);
  }finally{await rpc.disconnect();}
  const fees=rust(logs,'fees',['fees']);assert.equal(fees.minimum_note,26713000);assert.equal(fees.minimum_native_payout,10000000);
  const m=read(path.join(publicDir,'manifest.json')),w=startWallet(root,0);
  try{
    await w.ready;
    const result=await w.request({through:1,kind:'transfer',spend_cm:Buffer.from(m.initial_state.commitments[0]).toString('hex'),recipient:m.receivers[1],amount:String(fees.minimum_note)});
    assert.equal(result.report.step,2);
    for(const suffix of ['.json','.metrics.json'])fs.copyFileSync(path.join(w.out,'0002'+suffix),path.join(publicDir,'0002'+suffix),fs.constants.COPYFILE_EXCL);
    await w.close();
  }catch(e){w.kill();throw e;}
  const transactions={};for(let s=0;s<=2;s++){const p=path.join(publicDir,number(s)+'.json');transaction(read(p)).free();transactions[number(s)]=fileHash(p);}
  const prepared={purpose,createdAt:new Date().toISOString(),network:'testnet-10',binarySha256:fileHash(binary),sources,transactions,minimumNoteSompi:String(fees.minimum_note),minimumPayoutSompi:String(fees.minimum_native_payout),scope:'bootstrap prepared; future exits generated by isolated autonomous wallets during live test'};
  save(path.join(root,'prepared.json'),prepared);console.log(JSON.stringify({stage:'prepared',root,broadcast:false}));
}
export function startAgent(root,index){
  const dir=path.join(root,'agents',String(index));fs.mkdirSync(dir,{recursive:true,mode:0o700});
  fs.mkdirSync(path.join(dir,'public'),{mode:0o700});fs.mkdirSync(path.join(dir,'wallet0'),{mode:0o700});
  for(const name of ['pk.bin','vk.bin','manifest.json','source-utxo.json','0000.json','0001.json','0002.json','0000.metrics.json','0001.metrics.json','0002.metrics.json']){
    fs.copyFileSync(path.join(root,'public',name),path.join(dir,'public',name),fs.constants.COPYFILE_EXCL);
  }
  save(path.join(dir,'seed.json'),{network:'testnet-10',through:2,anchor:read(path.join(root,'anchor.json')).sink});
  // The writable agent directory contains no copied wallet secrets. The only
  // private file is mounted read-only, under the same neutral path for either.
  fs.writeFileSync(path.join(dir,'wallet0','wallet.json'),'',{mode:0o600,flag:'wx'});
  const prover=startWalletSidecar(dir,path.join(root,`wallet${index}/wallet.json`));
  const args=['--unshare-user','--unshare-pid','--unshare-ipc','--unshare-uts','--die-with-parent','--new-session','--clearenv','--ro-bind','/usr','/usr','--symlink','usr/bin','/bin','--symlink','usr/lib','/lib','--symlink','usr/lib64','/lib64','--proc','/proc','--dev','/dev','--tmpfs','/tmp','--setenv','PATH','/usr/bin:/bin','--setenv','KPI_BINARY','/software/kpi-shared-pool','--setenv','KPI_SDK_PATH','/sdk/kaspa.js','--setenv','KPI_TN10_RPC',process.env.KPI_TN10_RPC??'ws://10.0.3.26:17210','--dir','/software','--ro-bind',process.execPath,'/software/node','--ro-bind',path.resolve(binary),'/software/kpi-shared-pool','--ro-bind',here,'/software/src','--ro-bind',path.dirname(sdkPath),'/sdk','--bind',dir,'/trial','--ro-bind',path.join(root,`wallet${index}/wallet.json`),'/trial/wallet0/wallet.json','--ro-bind',path.join(root,'barrier'),'/barrier','--chdir','/trial','--','/software/node','/software/src/exit-wallet.mjs','/trial'];
  const out=fs.openSync(path.join(dir,'stdout.log'),'wx',0o600),err=fs.openSync(path.join(dir,'stderr.log'),'wx',0o600);
  args.splice(args.indexOf('--dir'),0,'--setenv','KPI_PROVER_CHANNEL','/trial/channel');
  const child=spawn('bwrap',args,{stdio:['ignore',out,err]});fs.closeSync(out);fs.closeSync(err);
  let failure,closed=false;
  const agentDone=new Promise((resolve,reject)=>{child.on('error',e=>{failure=e;reject(e);});child.on('close',code=>{
    closed=true;save(path.join(dir,'process-exit.json'),{code,observedAt:new Date().toISOString()});
    if(code!==0){failure=Error(`agent ${index} failed; ${dir}/stderr.log`);reject(failure);}else resolve();
  });});
  prover.done.catch(e=>{failure=e;});const done=Promise.all([agentDone,prover.done]);done.catch(()=>{});
  return {dir,done,async stop(){if(!closed)child.kill('SIGTERM');prover.kill();await Promise.allSettled([agentDone,prover.done]);},async ready(){while(!fs.existsSync(path.join(dir,'ready.json'))){if(failure)throw failure;assert.ok(!closed,'agent exited before readiness');await sleep(1000);}return read(path.join(dir,'ready.json'));}};
}
async function live(root){
  const prepared=read(path.join(root,'prepared.json'));assert.equal(prepared.binarySha256,fileHash(binary));assert.deepEqual(prepared.sources,sourceHashes());
  for(const [s,h] of Object.entries(prepared.transactions))assert.equal(fileHash(path.join(root,'public',s+'.json')),h);
  const liveDir=path.join(root,'live');fs.mkdirSync(liveDir,{mode:0o700});syncDirectory(root);
  const {rpc,info}=await connect();const source=read(path.join(root,'funding-input.json')),ledger=new Map([[outpoint(source),source]]);let fee=0n;const agents=[];
  try{
    save(path.join(liveDir,'node.json'),{info,feeEstimate:await rpc.getFeeEstimate()});
    const dag=await rpc.getBlockDagInfo();save(path.join(root,'anchor.json'),{sink:dag.sink,capturedAt:new Date().toISOString()});
    const chain=[];
    for(let s=0;s<=2;s++){
      const p=path.join(root,'public',number(s)+'.json'),raw=read(p),inputs=[];
      for(const i of raw.inputs){const key=`${i.previousOutpoint.transactionId}:${i.previousOutpoint.index}`,expected=ledger.get(key);assert.ok(expected);const actual=await exactUtxo(rpc,expected);assert.ok(actual);inputs.push(actual);ledger.delete(key);}
      const ctx=path.join(liveDir,number(s)+'.inputs.json');save(ctx,inputs);
      const val=rust(liveDir,number(s)+'-validate',['validate',p,ctx]);fee+=BigInt(val.metrics.fee_sompi);
      const tx=transaction(raw);save(path.join(liveDir,number(s)+'.submission.json'),{txid:raw.id,submittedAt:new Date().toISOString()});
      try{const response=await rpc.submitTransaction({transaction:tx,allowOrphan:false});assert.equal(response.transactionId,raw.id);save(path.join(liveDir,number(s)+'.response.json'),{accepted:true,response});}
      catch(error){save(path.join(liveDir,number(s)+'.response.json'),{accepted:false,error:String(error)});throw error;}finally{tx.free();}
      const outputs=await confirm(rpc,raw);for(const u of outputs)ledger.set(outpoint(u),u);
      save(path.join(liveDir,number(s)+'.confirmed.json'),{observedAt:new Date().toISOString(),outputs});chain.push({step:s,tx:raw,inputs});
      console.log(JSON.stringify({stage:'seed-confirmed',step:s,txid:raw.id}));
    }
    fs.mkdirSync(path.join(root,'barrier'),{mode:0o700});
    for(const i of [0,1])agents.push(startAgent(root,i));
    const ready=await Promise.all(agents.map(a=>a.ready()));
    assert.deepEqual(ready[0].predecessor,ready[1].predecessor);
    assert.equal(ready[0].predecessor.transactionId,chain[2].tx.id);
    assert.notEqual(ready[0].txid,ready[1].txid);
    assert.ok(await exactUtxo(rpc,outputUtxo(chain[2].tx,0)));
    save(path.join(root,'barrier','go.json'),{releasedAt:new Date().toISOString()});
    console.log(JSON.stringify({stage:'race-released',sameReserve:ready[0].predecessor}));
    // No more controller writes to wallet inputs or messages to either wallet.
    await Promise.all(agents.map(a=>a.done));
    const results=agents.map(a=>read(path.join(a.dir,'result.json')));
    assert.deepEqual(results.map(r=>r.rebuilds).sort(),[0,1]);assert.ok(results.every(r=>r.ownNotesRemaining===0&&r.proverClosed));
    const snapshot=await acceptedSnapshot(rpc,dag.sink);
    for(const row of chain){const found=snapshot.transactions.find(x=>x.transaction.verboseData?.transactionId===row.tx.id);assert.ok(found);assert.deepEqual(canonicalRpcTx(found.transaction),row.tx);}
    let reserve=outputUtxo(chain[2].tx,0);
    const accepted=[];
    while(reserve){
      const found=successor(snapshot,reserve);assert.ok(found,'accepted successor missing');
      const raw=canonicalRpcTx(found.transaction),step=chain.length,p=path.join(liveDir,number(step)+'.json');transaction(raw).free();
      const prior=ledger.get(outpoint(reserve));assert.ok(prior);save(p,raw);
      const ctx=path.join(liveDir,number(step)+'.inputs.json');save(ctx,[prior]);
      const val=rust(liveDir,number(step)+'-validate',['validate',p,ctx]);assert.equal(val.full_hash,found.transaction.verboseData.hash);
      fee+=BigInt(val.metrics.fee_sompi);ledger.delete(outpoint(reserve));
      for(let i=0;i<raw.outputs.length;i++){const u=outputUtxo(raw,i);ledger.set(outpoint(u),u);}
      chain.push({step,tx:raw,inputs:[prior]});accepted.push(found);
      reserve=Buffer.from(raw.payload,'hex')[8]===3?null:outputUtxo(raw,0);
    }
    assert.equal(accepted.length,2);assert.equal(chain.length,5);
    assert.deepEqual(new Set(accepted.map(x=>x.transaction.verboseData.transactionId)),new Set(results.map(r=>r.acceptedTxid)));
    const remaining=[];for(const u of ledger.values()){const actual=await exactUtxo(rpc,u);assert.ok(actual,'final native payout/change missing');remaining.push(actual);}
    const remainingSum=remaining.reduce((n,u)=>n+BigInt(u.amount),0n);assert.equal(remainingSum+fee,BigInt(source.amount));
    assert.equal(await exactUtxo(rpc,outputUtxo(chain[3].tx,0)),undefined,'terminal reserve remains');
    const submissions=agents.map(a=>read(path.join(a.dir,'attempt-0.submission.json')));
    const skew=Math.abs(Date.parse(submissions[0].submittedAt)-Date.parse(submissions[1].submittedAt));
    const loser=results.findIndex(r=>r.rebuilds===1),winner=1-loser;
    const recovery=read(path.join(agents[loser].dir,'attempt-1.proof.json'));
    const winnerExit=read(path.join(agents[winner].dir,'process-exit.json'));
    const winnerStoppedBeforeLoserPayout=Date.parse(winnerExit.observedAt)<=Date.parse(results[loser].payoutConfirmedAt);
    const result={success:winnerStoppedBeforeLoserPayout,completedAt:new Date().toISOString(),purpose:prepared.purpose,network:'testnet-10',confirmedTransactions:5,submittedTransactions:6,acceptedFeeSompi:fee.toString(),rejectedCandidateFeeSompi:'0',sameReserveRace:true,submissionSkewMs:skew,winner,loser,wallets:results,winnerStoppedBeforeLoserPayout,winnerProcessExitedBeforeRecoveryProofCompleted:Date.parse(winnerExit.observedAt)<=Date.parse(recovery.completedAt),terminalReserveSpent:true,remainingOutputs:remaining,startingSompi:source.amount,remainingSompi:remainingSum.toString(),sourceHashes:prepared.sources,binarySha256:prepared.binarySha256,scope:'two-wallet one-shot contention with eventual opportunity; single-node accepted view; not arbitrary reorg recovery, fairness, mainnet safety or anonymity'};
    save(path.join(root,'chain-confirmed.json'),{schema:'kpi-shared-pool-contention-chain-v3',network:'testnet-10',transactions:chain});
    save(path.join(root,'chain-retrieval.json'),{observedAt:snapshot.observedAt,pages:snapshot.pages,accepted,source:'Full accepted data matched by reserve lineage'});
    save(path.join(root,'result.json'),result);assert.ok(result.success,'payouts confirmed, but winner-stop independence condition was not met');console.log(JSON.stringify({stage:'complete',root,confirmed:5,feeSompi:fee.toString(),winner,loser,submissionSkewMs:skew,bothExited:true}));
  }finally{await Promise.allSettled(agents.map(a=>a.stop()));await rpc.disconnect();}
}
if(path.resolve(process.argv[1]??'')===path.join(here,'contention.mjs')){
  const [command,a,b,c]=process.argv.slice(2);
  try{
    if(command==='prepare'&&a&&b&&c)await prepare(path.resolve(a),path.resolve(b),c);
    else if(command==='live'&&a)await live(path.resolve(a));
    else throw Error('usage: node contention.mjs prepare PARAMS BASE rehearsal|trial | live ROOT');
  }catch(e){console.error(e.stack??String(e));process.exitCode=1;}
}
